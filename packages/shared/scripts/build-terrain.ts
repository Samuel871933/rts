/**
 * Builds src/data/terrain.generated.ts from the map geometry authored in src/data/mapGeometry.ts.
 * Unlike the old build-terrain.py (which traced the official Summoner's Rift minimap), this
 * rasterizes our own original layout, so terrain/lanes/jungle/river all come from one source.
 *
 * Usage: node packages/shared/scripts/build-terrain.ts (Node 22.6+ runs TypeScript natively)
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { MAP_SIZE } from '../src/constants.ts';
import { closestOnPath, closestOnSegment, dist, type Vec2 } from '../src/math.ts';
import { CAMPS, LANE_PATHS } from '../src/data/map.ts';
import { STRUCTURES } from '../src/data/structures.ts';
import {
  BARON_POS,
  BASE_POLYGONS,
  DRAGON_POS,
  JUNGLE_ALCOVES,
  JUNGLE_LINKS,
  JUNGLE_LINK_WIDTH,
  NEXUS_POS,
  RIVER_PATH,
  RIVER_PIT_RADIUS,
  RIVER_WIDTH,
  TUNNEL_PATH,
  TUNNEL_WIDTH,
} from '../src/data/mapGeometry.ts';

const TERRAIN_RES = 512;
const CELL = MAP_SIZE / TERRAIN_RES;
const JUNGLE_CORRIDOR_WIDTH = 520;

const WALL = '#';
const GROUND = '.';
const RIVER = '~';
const BASE = 'b';

function pointInPolygon(p: Vec2, poly: Vec2[]): boolean {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const a = poly[i];
    const b = poly[j];
    const intersects = a.y > p.y !== b.y > p.y && p.x < ((b.x - a.x) * (p.y - a.y)) / (b.y - a.y) + a.x;
    if (intersects) inside = !inside;
  }
  return inside;
}

function distToPath(p: Vec2, path: Vec2[]): number {
  let best = Infinity;
  for (let i = 0; i < path.length - 1; i++) best = Math.min(best, dist(p, closestOnSegment(p, path[i], path[i + 1]).point));
  return best;
}

const laneConnectors = JUNGLE_ALCOVES.map((a) => [a.center, closestOnPath(a.center, LANE_PATHS[a.backbone]).point] as const);

function classify(p: Vec2): string {
  if (pointInPolygon(p, BASE_POLYGONS.blue) || pointInPolygon(p, BASE_POLYGONS.red)) return BASE;
  if (distToPath(p, RIVER_PATH) <= RIVER_WIDTH / 2) return RIVER;
  if (dist(p, BARON_POS) <= RIVER_PIT_RADIUS || dist(p, DRAGON_POS) <= RIVER_PIT_RADIUS) return RIVER;
  for (const lane of Object.values(LANE_PATHS)) if (distToPath(p, lane) <= 900 / 2) return GROUND;
  if (distToPath(p, TUNNEL_PATH) <= TUNNEL_WIDTH / 2) return GROUND;
  for (const alcove of JUNGLE_ALCOVES) if (dist(p, alcove.center) <= alcove.radius) return GROUND;
  for (const [a, b] of laneConnectors) if (dist(p, closestOnSegment(p, a, b).point) <= JUNGLE_CORRIDOR_WIDTH / 2) return GROUND;
  for (const { a, b } of JUNGLE_LINKS) if (dist(p, closestOnSegment(p, a, b).point) <= JUNGLE_LINK_WIDTH / 2) return GROUND;
  return WALL;
}

function rle(cells: string[]): string {
  const out: string[] = [];
  let run = cells[0];
  let count = 0;
  for (const c of cells) {
    if (c === run) count++;
    else {
      out.push(`${count}${run}`);
      run = c;
      count = 1;
    }
  }
  out.push(`${count}${run}`);
  return out.join('');
}

function main() {
  const cells: string[] = new Array(TERRAIN_RES * TERRAIN_RES);
  let i = 0;
  // Row 0 = bottom of the map (world y = 0), matching terrain.ts's decoding order.
  for (let row = 0; row < TERRAIN_RES; row++) {
    const y = (row + 0.5) * CELL;
    for (let col = 0; col < TERRAIN_RES; col++) {
      const x = (col + 0.5) * CELL;
      cells[i++] = classify({ x, y });
    }
  }
  const encoded = rle(cells);
  const out = fileURLToPath(new URL('../src/data/terrain.generated.ts', import.meta.url));
  writeFileSync(
    out,
    "// Generated by scripts/build-terrain.ts from src/data/mapGeometry.ts: do not edit.\n" +
      `export const TERRAIN_RES = ${TERRAIN_RES};\n` +
      "/** Run-length encoded rows (bottom row first): '#' wall, '.' ground, '~' river, 'b' base. */\n" +
      `export const TERRAIN_RLE =\n  '${encoded}';\n`,
  );
  console.log(`terrain.generated.ts: ${TERRAIN_RES}x${TERRAIN_RES}, ${encoded.length} chars`);
}

/** Same geometry, as JSON, for the Blender block-out script (scripts/blender/build_map.py). */
function writeGeometryJson() {
  const geometry = {
    mapSize: MAP_SIZE,
    basePolygons: BASE_POLYGONS,
    nexusPos: NEXUS_POS,
    lanePaths: LANE_PATHS,
    laneWidth: 900,
    riverPath: RIVER_PATH,
    riverWidth: RIVER_WIDTH,
    riverPitRadius: RIVER_PIT_RADIUS,
    baronPos: BARON_POS,
    dragonPos: DRAGON_POS,
    tunnelPath: TUNNEL_PATH,
    tunnelWidth: TUNNEL_WIDTH,
    jungleAlcoves: JUNGLE_ALCOVES.map((a) => ({
      center: a.center,
      radius: a.radius,
      connector: closestOnPath(a.center, LANE_PATHS[a.backbone]).point,
    })),
    jungleLinks: JUNGLE_LINKS,
    jungleLinkWidth: JUNGLE_LINK_WIDTH,
    camps: CAMPS,
    structures: STRUCTURES.map((s) => ({ id: s.id, kind: s.kind, team: s.team, tier: s.tier, pos: s.pos })),
  };
  const out = fileURLToPath(new URL('../src/data/mapGeometry.generated.json', import.meta.url));
  writeFileSync(out, JSON.stringify(geometry, null, 2));
  console.log(`mapGeometry.generated.json written (${CAMPS.length} camps, ${JUNGLE_ALCOVES.length} alcoves)`);
}

main();
writeGeometryJson();
