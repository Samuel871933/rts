"""
Builds src/data/terrain.generated.ts from the official Summoner's Rift minimap (Data Dragon).

Every pixel is classified as wall / ground / river / base; the grid is stored run-length encoded,
row 0 = bottom of the map (world y = 0). Placeholder terrain until MacroGod has its own map.

Usage: python3 packages/shared/scripts/build-terrain.py [path/to/map11.png]
(without a path, the minimap is downloaded from Data Dragon). Requires Pillow.
"""
import io
import math
import sys
import urllib.request
from pathlib import Path

from PIL import Image

DDRAGON_MAP = 'https://ddragon.leagueoflegends.com/cdn/14.24.1/img/map/map11.png'
OUT = Path(__file__).resolve().parent.parent / 'src' / 'data' / 'terrain.generated.ts'

WALL, GROUND, RIVER, BASE = '#', '.', '~', 'b'


def classify(r: int, g: int, b: int, corner_dist: float) -> str:
    """corner_dist: distance to the nearest base corner, as a share of the image size."""
    if (r + g + b) / 3 < 70:
        return WALL
    # Grey-blue = base, but only around the corners: elsewhere it is a river / ground blend.
    if b - r > 20 and corner_dist < 0.42:
        return RIVER if b - r > 70 and g > 120 else BASE
    if b - r > 40:
        return RIVER
    return GROUND


def load(argv: list[str]) -> Image.Image:
    if len(argv) > 1:
        return Image.open(argv[1])
    with urllib.request.urlopen(DDRAGON_MAP) as res:
        return Image.open(io.BytesIO(res.read()))


def rle(cells: list[str]) -> str:
    out: list[str] = []
    run, count = cells[0], 0
    for c in cells:
        if c == run:
            count += 1
        else:
            out.append(f'{count}{run}')
            run, count = c, 1
    out.append(f'{count}{run}')
    return ''.join(out)


def main() -> None:
    im = load(sys.argv).convert('RGB')
    size = im.width
    px = im.load()
    def corner_dist(x: int, y: int) -> float:
        # Bases: bottom-left (blue) and top-right (red) corners, in world orientation (y up).
        return min(math.hypot(x, y), math.hypot(size - x, size - y)) / size

    cells = [classify(*px[x, size - 1 - y], corner_dist(x, y)) for y in range(size) for x in range(size)]
    encoded = rle(cells)
    OUT.write_text(
        '// Generated by scripts/build-terrain.py from the Summoner\'s Rift minimap: do not edit.\n'
        f'export const TERRAIN_RES = {size};\n'
        "/** Run-length encoded rows (bottom row first): '#' wall, '.' ground, '~' river, 'b' base. */\n"
        f"export const TERRAIN_RLE =\n  '{encoded}';\n"
    )
    print(f'{OUT.name}: {size}x{size}, {len(encoded)} chars')


if __name__ == '__main__':
    main()
